import 'package:flutter/widgets.dart';

/// Пороги ширины, по которым выбирается компоновка.
abstract class AppBreakpoints {
  /// С этой ширины показывается десктопная оболочка.
  ///
  /// Макет рассчитан на 1440+ (база 1728), но до 1200 таблица из шести колонок
  /// и сайдбар 252px ещё помещаются без горизонтальной прокрутки. Ниже сжимать
  /// нечего: получилось бы нечитаемо и то, и другое — там работает мобильная
  /// компоновка, которая для узкого экрана и рисовалась.
  static const double desktop = 1200;
}

extension ResponsiveContext on BuildContext {
  /// Экран достаточно широкий для десктопной компоновки.
  ///
  /// Смотрим на ширину окна, а не на платформу: окно Windows-приложения
  /// пользователь волен сузить до половины экрана, и тогда правильный ответ —
  /// мобильная компоновка, а не сломанные таблицы.
  bool get isDesktopWidth =>
      MediaQuery.sizeOf(this).width >= AppBreakpoints.desktop;
}

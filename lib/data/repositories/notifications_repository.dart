import '../models/notification_event.dart';

/// Контракт потока уведомлений (`/*/notifications/stream`).
///
/// Ролей две, и поток у каждой свой: админу приходят события по всем
/// водителям, водителю — только его собственные. Реализация выбирается
/// в `app.dart` вместе с остальными репозиториями роли, поэтому экран
/// про чужой поток даже не знает.
///
/// Реализации: [ApiNotificationsRepository] и [MockNotificationsRepository].
abstract class NotificationsRepository {
  /// События сервера. Broadcast: слушают и списки, и открытая карточка.
  ///
  /// Поток бесконечен и молчалив — ошибки соединения в него не приходят,
  /// с ними разбирается транспорт (переподключение, докачка по
  /// `Last-Event-ID`). Экрану остаётся решить, что перечитать.
  Stream<NotificationEvent> get events;

  /// Отпускает соединение. Вызывается, когда роль уходит из дерева.
  Future<void> dispose();
}

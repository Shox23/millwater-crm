/// Ключ идемпотентности для одной попытки создания записи.
///
/// Сервер принимает заголовок `Idempotency-Key` на всех create-эндпоинтах и
/// по нему отличает повтор от новой записи. Поэтому ключ генерируется
/// один раз на экран формы и переживает повторные нажатия «Создать»: после
/// обрыва связи уйдёт тот же ключ, и второй водитель/заказчик/маршрут не
/// появится. Новая форма — новый ключ.
///
/// Формат — префикс и микросекунды: читаемо в логах сервера и уникально
/// в пределах устройства.
String newIdempotencyKey(String prefix) =>
    '$prefix-${DateTime.now().microsecondsSinceEpoch}';

/// Порядок объезда точек маршрута.
///
/// Сервер точки по `sequence` **не сортирует**: он проставляет номер при
/// создании, умеет его менять (`PATCH …/customers/{id}/sequence`), но отдаёт
/// записи в порядке `created_at`. То есть порядок, который админ задал в
/// маршруте, до водителя сам по себе не доезжает — его восстанавливает клиент.
///
/// Правило одно на всё приложение: по возрастанию номера, записи без номера —
/// в конец, при равных номерах сохраняется порядок ответа. Три места считали
/// это по-своему (карта строила по `sequence`, сборка маршрута из заказов —
/// по `sequence ?? 0`, то есть безномерные шли первыми, а список точек не
/// сортировал вовсе), и порядок объезда зависел от того, каким экраном на него
/// смотрят.
///
/// Сортировка устойчивая: список сначала размечается исходными индексами, и
/// при равных ключах сравниваются они. `List.sort` устойчивости не обещает.
List<T> inVisitOrder<T>(List<T> items, int? Function(T item) sequenceOf) {
  final indexed = items.indexed.toList();

  indexed.sort((a, b) {
    final left = sequenceOf(a.$2);
    final right = sequenceOf(b.$2);
    if (left != null && right != null && left != right) {
      return left.compareTo(right);
    }
    // Без номера — в конец; при равных номерах порядок ответа сохраняется.
    if (left == null && right != null) return 1;
    if (left != null && right == null) return -1;
    return a.$1.compareTo(b.$1);
  });

  return [for (final entry in indexed) entry.$2];
}

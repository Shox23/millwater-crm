import 'dart:math';

/// Стартовый пароль для новой учётной записи водителя.
///
/// Раньше здесь была константа, одна на всех (`123456`). Пока водитель не
/// сменил её сам, под его учёткой входил любой, кто знает номер телефона, —
/// а учётка водителя закрывает доставки и записывает суммы наличных.
///
/// Сбросить пароль админ не может: в API нет ни эндпоинта сброса, ни флага
/// «пароль временный». Поэтому сгенерированное значение обязано дойти до
/// водителя — форма показывает его до отправки и даёт скопировать.
abstract class DriverPassword {
  /// Алфавит без пар, которые путаются при чтении вслух и переписывании:
  /// нет `0`/`O`, `1`/`l`/`I`, `5`/`S`, `8`/`B`. Пароль диктуют по телефону,
  /// и «нолик или буква о» — это второй звонок.
  static const _alphabet = 'ACDEFGHJKLMNPQRTUVWXYZacdefghijkmnpqrtuvwxyz234679';

  /// Длина. Восьми символов из этого алфавита хватает: подобрать его онлайн
  /// нельзя, а переписать с экрана — можно.
  static const _length = 8;

  /// Криптостойкий источник: обычный [Random] предсказуем по времени старта,
  /// а пароли водителей заводятся пачками в один день.
  static final _random = Random.secure();

  /// Новый пароль для учётки водителя.
  static String generate() => String.fromCharCodes(
        Iterable.generate(
          _length,
          (_) => _alphabet.codeUnitAt(_random.nextInt(_alphabet.length)),
        ),
      );
}

import 'dart:async';

import 'package:flutter/foundation.dart';

/// Окно склейки для перезагрузок по событиям с сервера.
///
/// Одно на всех подписчиков: на десктопе на одно закрытие точки отзываются
/// сразу два блока, и разъедься у них окна — всплеск всё равно прошёл бы
/// дважды. Три секунды — компромисс: оператор не замечает задержки, а
/// утренний шквал сходится в одну перезагрузку.
const Duration kNotificationReloadWindow = Duration(seconds: 3);

/// Ограничитель частоты: первый вызов проходит сразу, остальные в течение
/// окна склеиваются в один.
///
/// Нужен подписчикам потока уведомлений. Раньше каждое событие с сервера
/// вызывало полную перезагрузку, а у админа на десктопе на одно закрытие
/// точки срабатывали сразу два блока — и каждый запрашивал список маршрутов
/// плюс детали каждого маршрута дня. В утренний час пик, когда десять
/// водителей закрывают точки подряд, это десятки полных перезагрузок одна
/// за другой.
///
/// Именно ограничитель, а не отсрочка: при отсрочке поток событий, идущий
/// чаще окна, откладывал бы перезагрузку бесконечно — список бы не
/// обновился вообще. Здесь же первое событие видно сразу, а хвост очереди
/// сходится в одну перезагрузку в конце окна.
class Throttle {
  Throttle(this.window);

  /// Сколько ждать после срабатывания, прежде чем пропустить следующее.
  final Duration window;

  Timer? _cooldown;
  VoidCallback? _pending;

  /// Выполняет [action] сразу либо откладывает до конца окна.
  ///
  /// Если за окно пришло несколько вызовов, выполнится только последний:
  /// все они означают одно и то же — «данные устарели, перечитай».
  void call(VoidCallback action) {
    if (_cooldown != null) {
      _pending = action;
      return;
    }
    action();
    _startCooldown();
  }

  void _startCooldown() {
    _cooldown = Timer(window, () {
      _cooldown = null;
      final pending = _pending;
      if (pending == null) return;
      _pending = null;
      pending();
      // Следующее окно начинается сразу: иначе после всплеска событий
      // ограничитель пропустил бы очередной шквал без задержки.
      _startCooldown();
    });
  }

  /// Отменяет отложенный вызов. Обязателен в `close()` блока: сработавший
  /// таймер обратился бы к закрытому блоку.
  void dispose() {
    _cooldown?.cancel();
    _cooldown = null;
    _pending = null;
  }
}

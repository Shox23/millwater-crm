/// Календарный день без времени.
///
/// Даты ходят между лентой, блоком и репозиторием только в таком виде: иначе
/// два одинаковых на вид дня с разным временем не равны друг другу, и экран
/// перезапрашивает то, что уже показывает.
DateTime dayOnly(DateTime value) =>
    DateTime(value.year, value.month, value.day);

/// Параметры продукта, которых нет в API.
abstract class ProductConfig {
  /// Объём капсулы, литров — используется только для подписи в интерфейсе.
  static const int capsuleVolumeLiters = 19;

  /// Цена одной капсулы, сум, — запасное значение на случай, когда прайса
  /// не добыть. По ней считается сумма оплаты при завершении доставки:
  /// капсулы × цена. Меняется без правки кода:
  /// `--dart-define=CAPSULE_PRICE=25000`.
  ///
  /// Основной источник — `CapsulePrice`: он спрашивает прайс у сервера и
  /// откатывается сюда молча. `/admin/prices/current` открыт **обеим ролям**
  /// (на сервере у ручки `CurrentUserDep`, а не `CurrentAdminDep`), так что
  /// и водитель считает по живой цене. Это значение остаётся на случай, когда
  /// прайса не добыть: связь пропала, сервер ответил ошибкой.
  ///
  /// Чего это значение не умеет — индивидуальной цены заказчика
  /// (`custom_water_price`). Она есть у сервера, но наружу в точке маршрута
  /// не отдаётся: поля `effective_water_price` в ответе нет, а
  /// `/admin/customers` водителю закрыт. Пока это не появится, у заказчика с
  /// личной ценой расчёт на экране и расчёт сервера разойдутся — и разницу
  /// сервер запишет заказчику в долг или предоплату.
  static const int capsulePrice =
      int.fromEnvironment('CAPSULE_PRICE', defaultValue: 20000);

  // Стартовый пароль водителя жил здесь константой, одной на всех. Теперь
  // он генерируется на каждую учётку — см. `DriverPassword.generate()`
  // в lib/core/utils/driver_password.dart.

  /// Водитель фиксирует координаты точки при завершении доставки.
  ///
  /// Выключено, пока в API нет полей `latitude`/`longitude` у заказчика:
  /// в схеме их нет ни у `RouteCustomerResponse`, ни в теле завершения
  /// доставки, а лишние поля в multipart сервер может отклонить с 422.
  ///
  /// С разрешением на геолокацию этот флаг не связан: оно объявлено в
  /// манифесте и Info.plist ради построения маршрута от места водителя
  /// (`BuildRouteSection`) и нужно независимо от того, включён ли флаг.
  ///
  /// Включать одновременно с появлением полей на сервере — тогда сразу
  /// заработают и запись координат, и построение маршрута в нативном
  /// приложении Яндекс.Карт по уже накопленным точкам.
  static const bool captureDeliveryCoordinates = false;
}

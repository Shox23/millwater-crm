/// Параметры продукта, которых нет в API.
abstract class ProductConfig {
  /// Объём капсулы, литров — используется только для подписи в интерфейсе.
  static const int capsuleVolumeLiters = 19;

  /// Цена одной капсулы, сум. По ней считается сумма оплаты при завершении
  /// доставки: капсулы × цена.
  ///
  /// Значение зашито в сборку, потому что цену отдаёт только админский
  /// `/admin/prices/current`, а водителю все `/admin/*` закрыты (403).
  /// Меняется без правки кода: `--dart-define=CAPSULE_PRICE=25000`.
  ///
  /// Когда бэкенд отдаст цену водителю — на `/driver/...` или прямо в точке
  /// маршрута — брать оттуда, а константу удалить: цена, живущая в сборке,
  /// расходится с прайсом ровно в день его изменения.
  static const int capsulePrice =
      int.fromEnvironment('CAPSULE_PRICE', defaultValue: 20000);

  /// Пароль, с которым заводится новая учётка водителя.
  ///
  /// Сервер требует пароль прямо в `CreateDriver`, а админского эндпоинта
  /// «сбросить пароль» в API нет. Поэтому водитель получает общий стартовый
  /// пароль и меняет его сам в настройках после первого входа.
  ///
  /// Пароль один на всех и никем не защищён: пока водитель его не сменил, под
  /// его учёткой войдёт любой, кто знает номер телефона. Значение подставляется
  /// в форму как заготовка — админ может ввести своё. Меняется без правки кода:
  /// `--dart-define=DEFAULT_DRIVER_PASSWORD=...`.
  static const String defaultDriverPassword = String.fromEnvironment(
    'DEFAULT_DRIVER_PASSWORD',
    defaultValue: '123456',
  );

  /// Водитель фиксирует координаты точки при завершении доставки.
  ///
  /// Выключено, пока в API нет полей `latitude`/`longitude` у заказчика:
  /// лишние поля в multipart сервер может отклонить с 422, а спрашивать
  /// у водителя разрешение на геолокацию ради выброшенных данных незачем.
  ///
  /// Включать одновременно с появлением полей на сервере — тогда сразу
  /// заработают и запись координат, и построение маршрута в нативном
  /// приложении Яндекс.Карт по уже накопленным точкам.
  static const bool captureDeliveryCoordinates = false;
}

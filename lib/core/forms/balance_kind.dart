/// Чем задан стартовый баланс заказчика.
///
/// Отдельное перечисление, а не два поля суммы: сервер держит инвариант
/// «либо долг, либо предоплата» (иначе 422 `BOTH_BALANCES_SET`), и в форме
/// он должен быть виден глазом, а не проверяться после отправки.
///
/// Общее для мобильной формы и десктопной модалки: два одинаковых
/// перечисления однажды разошлись бы, и разошлись бы молча.
enum BalanceKind { none, debt, prepayment }

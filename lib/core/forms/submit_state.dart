import 'package:flutter/widgets.dart';

/// Состояние отправки для экранов-форм: «идёт сохранение» и текст последней
/// неудачи.
///
/// Шесть форм держали одинаковые `_saving`, `_error` и `_failed(...)` — а
/// вместе с ними одинаковую проверку `mounted` после `await`, забыть которую
/// в седьмой раз ничего не стоит. Здесь это написано один раз.
///
/// Текст ошибки остаётся за экраном: коды у всех свои — занятый телефон у
/// заказчика, неверный текущий пароль при смене, чужой маршрут при завершении
/// доставки.
mixin SubmitState<T extends StatefulWidget> on State<T> {
  bool _submitting = false;
  String? _error;

  /// Идёт отправка: кнопку и поля пора заблокировать.
  bool get submitting => _submitting;

  /// Текст последней неудачи; `null` — показывать нечего.
  String? get submitError => _error;

  /// Выполняет [action], ведя за него флаг занятости и текст ошибки.
  ///
  /// Возвращает `true`, если сервер принял, — обычно вслед за этим экран
  /// закрывается. Флаг занятости при успехе намеренно не снимается: лишний
  /// кадр с ожившей кнопкой перед закрытием — это шанс на второе нажатие,
  /// а второе нажатие на форме создания означает вторую запись.
  ///
  /// [message] переводит исключение в текст для пользователя.
  Future<bool> submit(
    Future<void> Function() action, {
    required String Function(Object error) message,
  }) async {
    setState(() {
      _submitting = true;
      _error = null;
    });

    try {
      await action();
      return true;
    } catch (e) {
      // Экран обязан ожить: серая кнопка без объяснения — тупик, из которого
      // пользователю остаётся только убить приложение.
      if (mounted) {
        setState(() {
          _submitting = false;
          _error = message(e);
        });
      }
      return false;
    }
  }
}

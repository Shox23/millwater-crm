import 'package:dio/dio.dart';

/// Отделяет настоящие ошибки от ожидаемого шума.
///
/// Без этого фильтра трекер бесполезен. Водитель работает в дороге: связь
/// рвётся в подвале, во дворе-колодце и между вышками — десятки раз за смену.
/// Если слать всё подряд, то на одну ошибку, которую стоит чинить, придётся
/// несколько сотен «нет сети», и настоящая утонет в них вместе с квотой.
///
/// Правило простое: отправляем то, чего приложение не предусмотрело.
/// Всё, на что у него есть внятный ответ пользователю, — не инцидент.
bool isReportableError(Object? error) {
  if (error == null) return false;
  if (error is DioException) return _isReportableDioError(error);
  return true;
}

/// Разбор по видам сбоя, а не по признаку «был ли ответ»: молчание сервера
/// бывает и рабочим (нет сети), и тревожным (сертификату нельзя верить),
/// и валить их в одну кучу нельзя.
bool _isReportableDioError(DioException error) => switch (error.type) {
      // Отмену инициировали мы сами: остановка потока уведомлений, уход с
      // экрана до ответа. Это не сбой, а нормальное завершение.
      DioExceptionType.cancel => false,

      // Связи не было. Обычный день водителя, а не инцидент.
      DioExceptionType.connectionTimeout ||
      DioExceptionType.sendTimeout ||
      DioExceptionType.receiveTimeout ||
      DioExceptionType.connectionError =>
        false,

      // Отдельного типа под `SocketException` у dio нет — он заворачивает
      // её сюда же. Считаем недоступностью, как и `AuthRepository`, иначе
      // определения «сервер не ответил» разъедутся между слоями.
      DioExceptionType.unknown => false,

      // Сеть жива, но соединению нельзя доверять: просроченный сертификат
      // на сервере или чужой между нами и им. Это надо увидеть.
      DioExceptionType.badCertificate => true,

      // Ответ пришёл, а разбор не уложился в срок. Сеть тут ни при чём —
      // это наш собственный код не справился с телом ответа.
      DioExceptionType.transformTimeout => true,

      // Сервер ответил осмысленно, и приложение показало текст: занятый
      // телефон, неверный пароль, чужой маршрут, отлуп валидации. Чинить
      // нечего. А 5xx — сломался сервер: пользователь видит общую ошибку,
      // причина не на его стороне и сама не исправится.
      DioExceptionType.badResponse =>
        (error.response?.statusCode ?? 500) >= 500,
    };
